"""Write the edge-case PDFs the browser intake tests use (Vercel rebuild slice 4).

All derived from the fictional demo fixtures or blank; no real data. Encryption uses random salts, so these
files are committed once and not regenerated by scripts/verify.sh.
  encrypted.pdf                VIDEO-DEMO-001 locked with a user password ("secret")
  encrypted-no-password.pdf    VIDEO-DEMO-001 encrypted with an empty user password (opens without asking)
  no-text.pdf                  one page with a filled rectangle and no text (stands in for a scan)

Usage (from the repository root):
  backend/.venv/bin/python scripts/intake_fixtures.py
"""
from __future__ import annotations

import io
from pathlib import Path

from pypdf import PdfReader, PdfWriter
from reportlab.lib.pagesizes import LETTER
from reportlab.pdfgen import canvas

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "frontend" / "lib" / "intake" / "__fixtures__"
SOURCE = ROOT / "fixtures" / "demo" / "generated" / "VIDEO-DEMO-001.pdf"


def encrypted(user_password: str, owner_password: str) -> bytes:
    writer = PdfWriter()
    for page in PdfReader(str(SOURCE)).pages:
        writer.add_page(page)
    writer.encrypt(user_password, owner_password)
    buf = io.BytesIO()
    writer.write(buf)
    return buf.getvalue()


def no_text() -> bytes:
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=LETTER, invariant=1)
    c.rect(50, 50, 200, 200, fill=1)
    c.showPage()
    c.save()
    return buf.getvalue()


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "encrypted.pdf").write_bytes(encrypted("secret", "secret"))
    (OUT / "encrypted-no-password.pdf").write_bytes(encrypted("", "owner-fictional"))
    (OUT / "no-text.pdf").write_bytes(no_text())
    for name in ("encrypted.pdf", "encrypted-no-password.pdf", "no-text.pdf"):
        reader = PdfReader(str(OUT / name))
        print(name, "is_encrypted:", reader.is_encrypted)


if __name__ == "__main__":
    main()
