"""Record what the Python prototype's read endpoints return after the 15-step guided demo (rebuild slice 5).

The new screens read the run through frontend/lib/domain/selectors.ts instead of these endpoints; the Vitest
selectors test compares the two, timestamps aside. Uses the labelled TEST ADAPTER and a throwaway data folder.

Usage (from the repository root):
  backend/.venv/bin/python scripts/read_models.py [out.json]
  (default out: frontend/lib/domain/__fixtures__/read-models.json)
"""
from __future__ import annotations

import json
import logging
import os
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
os.environ["ORDER_AGENT_LOAD_DOTENV"] = "0"
os.environ["ORDER_AGENT_EXTRACTOR"] = "test"
os.environ.pop("GEMINI_API_KEY", None)
os.environ["ORDER_AGENT_DATA_DIR"] = tempfile.mkdtemp(prefix="order-agent-read-models-")
sys.path.insert(0, str(ROOT / "backend"))

from fastapi.testclient import TestClient  # noqa: E402

from app.config import load_settings  # noqa: E402
from app.main import create_app  # noqa: E402

logging.disable(logging.INFO)
# Timestamps differ on every run; they are masked so the file is reproducible and verify.sh can check it.
ISO = re.compile(r"\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(?:\.\d+)?(?:Z|[+-]\d\d:\d\d)")


def mask(value):
    if isinstance(value, str):
        return ISO.sub("<time>", value)
    if isinstance(value, list):
        return [mask(v) for v in value]
    if isinstance(value, dict):
        return {k: mask(v) for k, v in value.items()}
    return value


ADMIN = {"X-Demo-Role": "administrator", "X-Demo-User": "alex"}
REVIEWER = {"X-Demo-Role": "reviewer", "X-Demo-User": "rita"}


def main(out: Path) -> None:
    with TestClient(create_app(load_settings())) as c:
        def ok(r):
            assert r.status_code < 300, (r.status_code, r.text)
            return r.json()

        def decide(doc, key, action, reason=None, params=None):
            ok(c.post(f"/api/documents/{doc}/decisions", headers=REVIEWER,
                      json={"issue_key": key, "action": action, "reason": reason, "params": params or {}}))

        ok(c.post("/api/demo/reset", headers=ADMIN))
        ok(c.put("/api/demo/rehearsal-mode", headers=ADMIN, json={"value": "on"}))
        ok(c.put("/api/policy", headers=ADMIN, json={"mode": "exception_only"}))
        ok(c.post("/api/demo/forward/VIDEO-DEMO-001"))
        decide(1, "moq_violation:0", "one_off_exception", "Customer confirmed a one-off trial quantity (fictional)")
        decide(1, "price_mismatch:1", "accept_printed_price", "Promotional price agreed by the account manager (fictional)")
        decide(1, "outdated_identifier:2", "apply_mapping", None, {"save_for_future": True})
        ok(c.post("/api/memory-rules/1/state", headers=ADMIN, json={"state": "active"}))
        ok(c.post("/api/demo/forward/VIDEO-DEMO-002"))
        ok(c.post("/api/demo/forward/VIDEO-DEMO-003"))
        ok(c.post("/api/memory-rules/1/state", headers=ADMIN,
                  json={"state": "revoked", "reason": "Supplier withdrew the notice (fictional)"}))
        ok(c.post("/api/demo/forward/VIDEO-DEMO-004"))
        ok(c.put("/api/policy", headers=ADMIN, json={"mode": "review_all"}))
        ok(c.post("/api/demo/forward/VIDEO-DEMO-005"))
        ok(c.put("/api/demo/erp-failure-mode", headers=ADMIN, json={"value": "timeout_next"}))
        ok(c.post("/api/documents/5/approve", headers=REVIEWER))
        ok(c.post("/api/documents/5/retry-delivery", headers=REVIEWER))
        ok(c.post("/api/demo/forward/VIDEO-DEMO-005"))

        docs = ok(c.get("/api/documents"))
        result = {
            "_note": "FICTIONAL TEST DATA. Generated by scripts/read_models.py from the Python prototype.",
            "documents": docs,
            "document": {str(d["id"]): ok(c.get(f"/api/documents/{d['id']}")) for d in docs},
            "text": {str(d["id"]): ok(c.get(f"/api/documents/{d['id']}/text")) for d in docs},
            "orders": ok(c.get("/api/orders")),
            "memory_rules": ok(c.get("/api/memory-rules")),
            "erp_orders": ok(c.get("/api/erp/orders")),
            "policy": ok(c.get("/api/policy")),
            "summary": ok(c.get("/api/summary")),
        }
    out.write_text(json.dumps(mask(result), indent=1, sort_keys=True) + "\n")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "frontend/lib/domain/__fixtures__/read-models.json")
