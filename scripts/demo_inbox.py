"""Write the fictional demo inbox as the TypeScript workflow tests receive it (Vercel rebuild slice 3).

For every bundled demo email, records what intake keeps: the envelope fields, and for each PDF its
display name, hash, size, page count and native page text (read the same way the backend reads it).
The browser will do this parsing itself in slice 4; until then the workflow tests use this file.

Usage (from the repository root):
  backend/.venv/bin/python scripts/demo_inbox.py [out.json]
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app.extraction import read_pdf_pages  # noqa: E402
from app.intake import _check_pdf, parse_eml, safe_display_name  # noqa: E402

OUT = ROOT / "frontend" / "lib" / "domain" / "__fixtures__" / "demo-inbox.json"
MAX = 10 * 1024 * 1024


def main() -> None:
    inbox = {"_label": "FICTIONAL TEST DATA generated by scripts/demo_inbox.py", "emails": {}}
    for path in sorted((ROOT / "fixtures" / "demo" / "generated").glob("*.eml")):
        raw = path.read_bytes()
        envelope, attachments = parse_eml(raw, MAX)
        inbox["emails"][path.stem] = {
            "envelope": {
                "messageId": envelope["message_id"], "sender": envelope["sender"],
                "receivedAt": envelope["received_at"], "subjectMetadata": envelope["subject_metadata"],
                "intakeMode": "local_forward_demo", "rawSha256": hashlib.sha256(raw).hexdigest(),
            },
            "attachments": [{
                "originalFilename": safe_display_name(a.filename), "sha256": hashlib.sha256(a.data).hexdigest(),
                "sizeBytes": len(a.data), "pageCount": _check_pdf(a.data, MAX), "pageText": read_pdf_pages(a.data),
            } for a in attachments],
        }
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else OUT
    out.write_text(json.dumps(inbox, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(inbox['emails'])} emails)")


if __name__ == "__main__":
    main()
